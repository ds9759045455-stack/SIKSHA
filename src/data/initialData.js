export function generateSeedStudents() {
  const students = [];
  let rollCounter = 101;

  CLASSES_LIST.forEach((cls) => {
    // Generate ~20-25 realistic student records per class for fast interactive browsing,
    // plus metadata to scale to 2500 total strength seamlessly
    const countForClass = 22;
    for (let i = 1; i <= countForClass; i++) {
      const isBoy = (i + cls.classNum.charCodeAt(0)) % 2 === 0;
      const firstName = isBoy
        ? FIRST_NAMES_BOYS[(i * 3 + parseInt(cls.classNum)) % FIRST_NAMES_BOYS.length]
        : FIRST_NAMES_GIRLS[(i * 5 + parseInt(cls.classNum)) % FIRST_NAMES_GIRLS.length];
      const lastName = LAST_NAMES[(i * 7 + parseInt(cls.classNum)) % LAST_NAMES.length];
      const fatherName = "Shri " + FIRST_NAMES_BOYS[(i + 4) % FIRST_NAMES_BOYS.length] + " " + lastName;
      const motherName = "Smt. " + FIRST_NAMES_GIRLS[(i + 6) % FIRST_NAMES_GIRLS.length] + " " + lastName;
      
      const admissionYear = 2024 - (parseInt(cls.classNum) - 6);
      const admissionNo = `MLIC-${admissionYear}-${String(rollCounter).padStart(4, "0")}`;
      const rollNo = i;
      const feeDue = (i % 5 === 0) ? 1700 : (i % 7 === 0 ? 3200 : 0);
      const feeStatus = feeDue === 0 ? "Paid" : (feeDue < 2000 ? "Partial" : "Overdue");
      const phone = `98${Math.floor(10000000 + Math.random() * 89999999)}`;
      const locality = LOCALITIES[(i + parseInt(cls.classNum)) % LOCALITIES.length];

      students.push({
        id: `STU-${admissionNo}`,
        admissionNo,
        rollNo,
        name: `${firstName} ${lastName}`,
        gender: isBoy ? "Male" : "Female",
        classNum: cls.classNum,
        section: cls.section,
        classId: cls.id,
        stream: cls.stream,
        fatherName,
        motherName,
        phone,
        address: locality,
        dob: `20${16 - parseInt(cls.classNum)}-0${(i % 9) + 1}-1${i % 8}`,
        bloodGroup: ["A+", "B+", "O+", "AB+", "O-"][(i + rollCounter) % 5],
        category: ["OBC", "General", "SC", "OBC", "General"][(i) % 5],
        feeStatus,
        feeDue,
        totalFeePaid: 8500 - feeDue,
        attendanceRate: Math.min(99, Math.max(68, 85 + ((i * 3) % 15) - ((i * 2) % 10))),
        todayStatus: (i % 9 === 0) ? "Absent" : (i % 14 === 0 ? "Late" : "Present"),
      });

      rollCounter++;
    }
  });

  return students;
}

